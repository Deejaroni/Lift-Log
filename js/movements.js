// Which hand-held weight to draw, from the name.
export function kindOf(name){
  const n = name.toLowerCase();
  return /kettlebell/.test(n) ? "kettlebell" : /dumbbell|goblet/.test(n) ? "dumbbell" : /cable|rope|pulley/.test(n) ? "cable"
    : /bodyweight|push-up|pull-up|chin-up|dip|plank|crunch|sit-up|raise/.test(n) && !/barbell|dumbbell|machine/.test(n) ? "none" : "barbell";
}
export function patternKey(name, muscle, sub){
  const s = `${(muscle||"").toLowerCase()}|${(sub||"").toLowerCase()}|${name.toLowerCase()}`;
  for(const [re, key] of RULES) if(re.test(s)) return key;
  return null;
}
// Delt head an exercise works, from its library subgroup or its pattern.
export function deltHead(sub, key){
  const m = /^(front|side|rear) delts/i.exec(sub||""); if(m) return m[1].toLowerCase();
  return key && PATTERNS[key] ? PATTERNS[key].head || null : null;
}
